package scan

import (
	"encoding/json"
	"fmt"

	"cveanalysis/internal/task"
)

func narrativePrompt(in Input, report task.Report, verdict string) string {
	raw, err := json.MarshalIndent(report, "", "  ")
	if err != nil {
		raw = []byte("{}")
	}
	return fmt.Sprintf(`Ты пишешь для аналитика подробный журнал того, как прошёл анализ. Это не короткий вердикт, а связный текст на русском.
Иди по шагам в том порядке, в котором анализ шёл, и не пропускай шаг, даже если он ничего не дал.
Пиши так, чтобы по тексту было видно, что сделали, что нашли и какой вывод из этого следует.

Обязательно отрази, если соответствующее поле есть в отчёте:
- есть ли go.mod и какой путь, или что go.mod нет и проект не на Go;
- заметки dapp/README.md: если dev_notes нет, напиши, что файла не было и шаг пропущен; если есть, перескажи заметки и скажи, относятся ли они к уязвимости;
- vendor, версия пакета и строки go.mod, если они есть;
- патч: запрошен ли он, сколько в нём файлов, и по каждому файлу из patch_files — found true или false и путь;
- поиск: grep.source (patch — фразы из diff, description — фразы из описания), сами фразы, число совпадений, файлы и что видно в кусках кода grep.excerpts;
- достижимость deadcode: по каждой функции символ, статус и общий вывод; если reach нет, напиши, что проверка не запускалась;
- предварительный вывод pre_verdict дословно;
- итоговый вердикт дословно и почему он такой;
- поле applicability не пересказывай другими словами: applicable значит уязвимость применима, not_applicable значит неприменима, uncertain значит неопределенно.

Не выдумывай файлы, версии, совпадения и цитаты, которых нет в отчёте. Если данных для шага нет, так и напиши.

Компонент: %s
Ветка: %s
CVE: %s
Пакет: %s

Итоговый вердикт:
%s

Отчёт:
%s
`, in.ComponentURL, in.Branch, in.CVEID, in.PackageName, verdict, raw)
}
